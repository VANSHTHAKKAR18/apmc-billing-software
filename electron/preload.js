const { contextBridge, ipcRenderer } = require('electron');

contextBridge.exposeInMainWorld('electronAPI', {
  minimize: () => ipcRenderer.send('window:minimize'),
  maximize: () => ipcRenderer.send('window:maximize'),
  close: () => ipcRenderer.send('window:close'),
  isMaximized: () => ipcRenderer.invoke('window:isMaximized'),
  checkPinExists: () => ipcRenderer.invoke('auth:checkPinExists'),
  setPin: (hash) => ipcRenderer.invoke('auth:setPin', hash),
  getPin: () => ipcRenderer.invoke('auth:getPin'),
  getHeaders: () => ipcRenderer.invoke('headers:getAll'),
  getDefaultHeader: () => ipcRenderer.invoke('headers:getDefault'),
  setDefaultHeader: (id) => ipcRenderer.invoke('headers:setDefault', id),
  getParties: () => ipcRenderer.invoke('parties:getAll'),
  getPartyById: (id) => ipcRenderer.invoke('parties:getById', id),
  createParty: (party) => ipcRenderer.invoke('parties:create', party),
  updateParty: (id, party) => ipcRenderer.invoke('parties:update', id, party),
  deleteParty: (id) => ipcRenderer.invoke('parties:delete', id),
  getPartyStats: (id) => ipcRenderer.invoke('parties:getStats', id),
  getInvoices: (filters) => ipcRenderer.invoke('invoices:getAll', filters),
  getInvoiceById: (id) => ipcRenderer.invoke('invoices:getById', id),
  createInvoice: (invoice) => ipcRenderer.invoke('invoices:create', invoice),
  updateInvoice: (id, inv) => ipcRenderer.invoke('invoices:update', id, inv),
  deleteInvoice: (id) => ipcRenderer.invoke('invoices:delete', id),
  duplicateInvoice: (id) => ipcRenderer.invoke('invoices:duplicate', id),
  getDashboardStats: () => ipcRenderer.invoke('dashboard:getStats'),
  generateReport: (f) => ipcRenderer.invoke('reports:generate', f),
  getSetting: (key) => ipcRenderer.invoke('settings:get', key),
  setSetting: (key, val) => ipcRenderer.invoke('settings:set', key, val),
  createBackup: () => ipcRenderer.invoke('backup:create'),
  restoreBackup: () => ipcRenderer.invoke('backup:restore'),
  autoBackup: () => ipcRenderer.invoke('backup:autoBackup'),
  deleteAllData: () => ipcRenderer.invoke('data:deleteAll'),
  printInvoice: (html) => ipcRenderer.invoke('invoice:print', html),
  savePdf: (n, html) => ipcRenderer.invoke('invoice:savePdf', n, html),
});
